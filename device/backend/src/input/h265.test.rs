#[test]
fn reads_the_picture_size() {
    assert_eq!(picture_size(SPS_1080), Some((1920, 1080)));
    assert_eq!(picture_size(SPS_360), Some((640, 360)));
    assert_eq!(picture_size(SPS_CROPPED), Some((642, 362)));
}

#[test]
fn a_cut_off_sps_has_no_size() {
    assert_eq!(picture_size(&SPS_1080[..12]), None);
    assert_eq!(picture_size(&[]), None);
}

#[test]
fn hands_out_the_latest_sps() {
    let mut p = ParamSets::new();
    assert_eq!(p.sps(), None);
    p.feed(&[VPS_NAL, SPS_1080, PPS_NAL].concat());
    assert_eq!(p.sps(), Some(SPS_1080));
}
